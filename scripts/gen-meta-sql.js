/**
 * Regenerates src/migrations/1729400000000-CreateMetaIntegrations.sql from
 * src/services/meta/schema-sql.ts, so the manual SQL and the TypeORM migration cannot drift.
 *
 *   node scripts/gen-meta-sql.js
 */
const fs = require("fs")
const path = require("path")

const root = path.join(__dirname, "..", "src")
const src = fs.readFileSync(path.join(root, "services/meta/schema-sql.ts"), "utf8")
/* The template literal after `META_SCHEMA_SQL = ` — not the first backtick in the file, because the
   header comment quotes names in backticks too. */
const start = src.indexOf("META_SCHEMA_SQL = `") + "META_SCHEMA_SQL = `".length
const sql = src.slice(start, src.lastIndexOf("`")).trim()
if (!sql.startsWith("CREATE SCHEMA")) throw new Error("could not find the schema SQL")

const out = `-- Manual equivalent of 1729400000000-CreateMetaIntegrations.ts
--
-- GENERATED by scripts/gen-meta-sql.js from src/services/meta/schema-sql.ts. Do not edit by hand.
--
-- Use this to apply ONLY this migration; the final INSERT registers it in TypeORM's ledger so
-- \`medusa migrations run\` will not apply it again. Additive: one new schema, \`meta\`; nothing
-- outside it is touched. Until applied, the Meta webhook answers 200 and does nothing, and the OPS
-- Instagram screens say the module is not installed.

BEGIN;

${sql}

INSERT INTO migrations (timestamp, name)
VALUES (1729400000000, 'CreateMetaIntegrations1729400000000')
ON CONFLICT DO NOTHING;

COMMIT;

-- To undo:
--   DROP SCHEMA IF EXISTS meta CASCADE;
--   DELETE FROM migrations WHERE timestamp = 1729400000000;
`
fs.writeFileSync(path.join(root, "migrations/1729400000000-CreateMetaIntegrations.sql"), out)
console.log("wrote migrations/1729400000000-CreateMetaIntegrations.sql")
